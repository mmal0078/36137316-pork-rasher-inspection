"""Rebuild the HTML documentation site in ``docs/``.

Runs pdoc on the ``porkinspect`` package and on every command-line script in
``scripts/``, runs the test suite with an HTML report, and writes a small
landing page (``docs/index.html``) linking them all.
GitHub Pages serves ``docs/`` from the ``main`` branch.

Usage::

    python scripts/build_docs.py
"""

from __future__ import annotations

import datetime
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
REPO_URL = "https://github.com/mmal0078/36137316-pork-rasher-inspection"

LANDING = """<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Pork rasher inspection docs</title>
<style>
body{{font:16px/1.55 system-ui,sans-serif;max-width:720px;margin:40px auto;padding:0 16px;color:#1f2328;background:#fff}}
a{{color:#0969da}} li{{margin:.4em 0}} .muted{{color:#59636e;font-size:14px}}
</style></head><body>
<h1>Pork rasher packaging inspection</h1>
<p>MMA3001 project: detecting packaging and meat-placement defects in conveyor images with a fine-tuned YOLOv8n detector.</p>
<ul>
<li><a href="porkinspect.html">API documentation</a>: every module and function of the <code>porkinspect</code> package, generated by pdoc from the docstrings</li>
<li>Command-line scripts (the pipeline, run in this order):<ul>
{scripts}
</ul></li>
<li><a href="test_report.html">Test report</a>: latest pytest run ({result})</li>
<li><a href="{repo}">Source code on GitHub</a>, with the README, results and notebooks</li>
</ul>
<p class="muted">Built {date}.</p>
</body></html>
"""


#: Scripts in pipeline order, each with a one-line description for the landing page.
SCRIPTS = {
    "prepare_data": "data audit and YOLO export",
    "train_yolo": "fine-tune YOLOv8 and save raw predictions (run on a GPU)",
    "analyse_run": "threshold choice, frame-level results and failure cases",
    "baseline": "hand-crafted features + decision tree / SVM / MLP",
    "compare": "detector vs baseline, with paired bootstrap and McNemar test",
    "compare_runs": "sensitivity runs (image size, model size)",
    "brightness_test": "robustness to brightness changes",
    "profile_pipeline": "cProfile, arithmetic intensity and roofline",
    "inspect_image": "run the trained model on one image",
    "build_docs": "rebuild this site",
}


def main() -> int:
    """Build the API docs and the test report, then write the landing page.

    Returns:
        The pytest exit code (0 if every test passed), so a failing test
        suite makes this script fail too.

    Raises:
        subprocess.CalledProcessError: If pdoc fails.
    """
    if DOCS.exists():
        shutil.rmtree(DOCS)
    env = {**os.environ, "PYTHONPATH": os.pathsep.join([str(ROOT / "src"), str(ROOT / "scripts")])}
    subprocess.run([sys.executable, "-m", "pdoc", "porkinspect", *SCRIPTS, "-o", str(DOCS),
                    "--docformat", "google"], check=True, env=env)
    t = subprocess.run([sys.executable, "-m", "pytest", "-q", f"--html={DOCS / 'test_report.html'}",
                        "--self-contained-html"], cwd=ROOT, capture_output=True, text=True)
    result = (t.stdout.strip().splitlines() or ["no output"])[-1]
    scripts = "\n".join(f'<li><a href="{n}.html"><code>{n}.py</code></a>: {d}</li>' for n, d in SCRIPTS.items())
    (DOCS / "index.html").write_text(LANDING.format(result=result, repo=REPO_URL, scripts=scripts,
                                                    date=datetime.date.today().isoformat()))
    print(result)
    return t.returncode


if __name__ == "__main__":
    raise SystemExit(main())
